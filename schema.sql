CREATE TABLE IF NOT EXISTS orders (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 order_number text NOT NULL UNIQUE,
 name text NOT NULL,
 email text NOT NULL,
 phone_number text,
 cake_selected boolean NOT NULL DEFAULT false,
 cupcake_selected boolean NOT NULL DEFAULT false,
 flavour text, filling text, cake_size text, design_type text,
 cupcake_topping text, cupcake_quantity integer NOT NULL DEFAULT 0,
 color_scheme text, message text, dietary text, occasion text,
 event_date date, event_time time,
 total_price numeric(12,2) NOT NULL DEFAULT 0,
 status text NOT NULL DEFAULT 'Quote Requested',
 created_at timestamptz NOT NULL DEFAULT now()
);
CREATE UNIQUE INDEX IF NOT EXISTS orders_number_lower_idx ON orders (lower(order_number));
